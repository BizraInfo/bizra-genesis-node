//! Type Generator for TypeScript Frontend
//!
//! This binary generates TypeScript type definitions from Rust structs
//! using the ts-rs crate. It exports types to be used by the frontend
//! for type-safe communication with the backend WebSocket API.

use std::fs;
use std::path::Path;

// Import our WebSocket types (this will trigger code generation)
#[allow(unused_imports)]
use bizra_genesis_node::websocket::types::*;

/// Wrapper to force type generation for all WebSocket types
#[allow(unused)]
struct TypeExport;

impl TypeExport {
    fn generate_websocket_types() -> Result<String, Box<dyn std::error::Error>> {
        let mut types_output = String::new();

        // Generate types for each struct/enum with #[ts(export)]
        // Note: The #[ts(export)] attributes on the actual types will handle the individual exports
        // This function just orchestrates the generation

        types_output.push_str("// Auto-generated TypeScript types from Rust WebSocket types\n");
        types_output.push_str("// Generated by src/bin/generate-types.rs\n\n");

        // The individual #[ts(export)] attributes on each type in src/websocket/types.rs
        // will generate the actual TypeScript code when cargo build runs.
        // Here we just provide a reference implementation.

        types_output.push_str("// Import the generated types from individual declaration files\n");
        types_output.push_str("// This file serves as a central export point\n\n");

        types_output.push_str("export type { WebSocketMessage } from './WebSocketMessage';\n");
        types_output.push_str("export type { MessageType } from './MessageType';\n");
        types_output.push_str("export type { AgentMessage } from './AgentMessage';\n");
        types_output.push_str("export type { AgentResponse } from './AgentResponse';\n");
        types_output.push_str("export type { TypingIndicator } from './TypingIndicator';\n");
        types_output.push_str("export type { PresenceUpdate } from './PresenceUpdate';\n");
        types_output.push_str("export type { PresenceStatus } from './PresenceStatus';\n");
        types_output.push_str("export type { AuthRequest } from './AuthRequest';\n");
        types_output.push_str("export type { AuthResponse } from './AuthResponse';\n");
        types_output.push_str("export type { ErrorMessage } from './ErrorMessage';\n\n");

        // Add utility types
        types_output.push_str("// Utility types for discriminated unions\n");
        types_output.push_str("export type WebSocketMessagePayload =\n");
        types_output.push_str("  | AgentMessage\n");
        types_output.push_str("  | AgentResponse\n");
        types_output.push_str("  | AuthRequest\n");
        types_output.push_str("  | AuthResponse\n");
        types_output.push_str("  | TypingIndicator\n");
        types_output.push_str("  | PresenceUpdate\n");
        types_output.push_str("  | ErrorMessage;\n\n");

        Ok(types_output)
    }
}

fn main() -> Result<(), Box<dyn std::error::Error>> {
    println!("🔧 Generating TypeScript types from Rust...");

    // Ensure the output directory exists
    let output_dir = Path::new("../../apps/dashboard/src/types/generated");
    fs::create_dir_all(output_dir)?;

    // Generate TypeScript types
    let types_output = TypeExport::generate_websocket_types()?;
    let output_path = output_dir.join("websocket.ts");

    fs::write(&output_path, types_output)?;

    println!(
        "✅ TypeScript types generated at: {}",
        output_path.display()
    );
    println!("📝 Note: Individual type declarations are generated by ts-rs during build");
    println!("🔨 Run 'cargo build' to generate the complete .d.ts declaration files");

    Ok(())
}
